"""Parsers that turn raw TLC / SANY output into the normalized documents the judge compares.

The SAME functions are applied to Java's output (when goldens are generated) and to tlc-rs's output
(when check.py runs), so Rust must print TLC-compatible text; see harness/SCHEMA.md.
Do NOT edit this file from the loop.
"""
from __future__ import annotations

import re

from common import ROOT

MSG_RE = re.compile(r"@!@!@STARTMSG (\d+):(\d+) @!@!@\r?\n(.*?)@!@!@ENDMSG \1 @!@!@\r?\n?", re.S)
ERROR, TLCBUG, WARNING, STATE = 1, 2, 3, 4

EXIT_NAMES = {0: "success", 10: "violation_assumption", 11: "violation_deadlock", 12: "violation_safety",
              13: "violation_liveness", 14: "violation_assert", 75: "failure_spec_eval", 76: "failure_safety_eval",
              77: "failure_liveness_eval", 150: "error_spec_parse", 151: "error_config_parse",
              152: "error_statespace_too_large", 153: "error_system", 255: "error"}
# exit codes whose counterexample is a shortest BFS path (its length is part of the verdict)
BFS_TRACE_EXITS = {11, 12, 14, 75, 76}
# codes that only frame a trace (kept in `error_codes`, but never the "first error")
FRAMING = {2121, 2264, 2103}
VIOLATION_RE = re.compile(r"^(?:Invariant|Action property|Property|Temporal properties?) (.+?) (?:is|was|were|are) violated")

_ROOT_FORMS = sorted({str(ROOT), str(ROOT).replace("\\", "/"), str(ROOT).replace("\\", "\\\\")}, key=len, reverse=True)
_JARTMP_RE = re.compile(r"[A-Za-z]:[\\/][^\s]*?[\\/]tlc-\d+[\\/]")
_HARNESS_TMP_RE = re.compile(r"<ROOT>[\\/]tmp[\\/]harness[\\/][^\s\\/]+")


def norm(s: str) -> str:
    """Whitespace-insensitive, path-insensitive form of a message or value."""
    for f in _ROOT_FORMS:
        s = s.replace(f, "<ROOT>")
    s = _HARNESS_TMP_RE.sub("<TMP>", s)
    s = _JARTMP_RE.sub("<JARTMP>/", s)
    s = s.replace("\\", "/") if "<ROOT>" in s or "<TMP>" in s else s
    return " ".join(s.split())


def _int(s: str):
    try:
        return int(s.replace(",", ""))
    except Exception:
        return None


SANY_MARKERS = [("***Parse Error***", "parse_error"), ("Lexical error", "lexical_error"),
                ("Semantic errors:", "semantic_errors"), ("Level errors", "level_errors"),
                ("Cannot find source file for module", "missing_module"), ("Fatal errors", "fatal"),
                ("*** Warnings:", "warnings"), ("Could not parse module", "could_not_parse")]
SANY_ERR_START = re.compile(r"(\*\*\*Parse Error\*\*\*|Lexical error|Semantic errors:|Level errors|\*\*\* Errors:|"
                            r"Fatal errors|\*\*\* Warnings:|Cannot find source file)")


def parse_state(text: str) -> dict:
    """Body of a 2217/2216 message: 'N: <label>' then either 'x = v' or '/\\ x = v' lines."""
    lines = text.rstrip("\n").split("\n")
    head = lines[0]
    m = re.match(r"^(\d+): (.*)$", head)
    st = {"n": int(m.group(1)) if m else None, "label": norm(m.group(2)) if m else norm(head), "vars": {}}
    body = "\n".join(lines[1:])
    chunks = re.split(r"(?m)^/\\ ", body) if body.lstrip().startswith("/\\") else [body]
    for c in chunks:
        c = c.strip()
        if not c:
            continue
        name, sep, val = c.partition(" = ")
        if sep:
            st["vars"][name.strip()] = norm(val)
        else:
            st["vars"]["<raw>"] = norm(c)
    return st


def parse_tlc(stdout: str, rc) -> dict:
    """Normalize the output of `tlc2.TLC -tool ...` (or `tlc-rs tlc -tool ...`)."""
    d = {"exit_code": rc, "exit_name": EXIT_NAMES.get(rc, f"exit_{rc}"), "messages": 0,
         "reached_sany_end": False, "reached_init": False, "init_distinct": None, "init_generated": None,
         "success": False, "first_error": None, "violation": None, "error_codes": [], "errors": [],
         "warnings": [], "generated": None, "distinct": None, "left": None, "depth": None, "outdegree": None,
         "trace": [], "trace_tail": None, "output": [], "sany_errors": None, "bug": False}
    pos, started, sany_chunks, in_sany = 0, False, [], False
    for m in MSG_RE.finditer(stdout):
        raw = stdout[pos:m.start()]
        if started:
            d["output"] += [norm(l) for l in raw.splitlines() if l.strip()]
        elif in_sany:
            sany_chunks.append(raw)
        pos = m.end()
        code, cls, text = int(m.group(1)), int(m.group(2)), m.group(3)
        d["messages"] += 1
        if code == 2220:
            in_sany = True
        elif code == 2219:
            in_sany, d["reached_sany_end"] = False, True
        elif code == 2185:
            started = True
        elif code == 2189:
            d["reached_init"] = True
        elif code in (2190, 2191, 2208):
            nums = [_int(x) for x in re.findall(r"\d[\d,]*", text.split(" at ")[0])]
            if code == 2190 and nums:
                d["init_distinct"] = d["init_generated"] = nums[0]
            elif len(nums) >= 2:
                d["init_generated"], d["init_distinct"] = nums[0], nums[1]
        elif code == 2199:
            mm = re.match(r"\s*([\d,]+) states generated, ([\d,]+) distinct states found, ([\d,]+) states left", text)
            if mm:
                d["generated"], d["distinct"], d["left"] = (_int(x) for x in mm.groups())
        elif code == 2194:
            mm = re.search(r"is (\d[\d,]*)", text)
            d["depth"] = _int(mm.group(1)) if mm else None
        elif code == 2268:
            d["outdegree"] = norm(text)
        elif code == 2193:
            d["success"] = True  # text holds fingerprint-collision estimates: never compared
        elif code in (2216, 2217):
            d["trace"].append(parse_state(text))
        elif code == 2218:
            d["trace_tail"] = {"kind": "stuttering", "text": norm(text)}
        elif code == 2122:
            d["trace_tail"] = {"kind": "back_to", "text": norm(text)}
        if cls == ERROR:
            d["error_codes"].append(code)
            d["errors"].append({"code": code, "text": norm(text)})
            if d["first_error"] is None and code not in FRAMING:
                d["first_error"] = code
                vm = VIOLATION_RE.match(norm(text))
                if vm:
                    d["violation"] = vm.group(1)
        elif cls == WARNING:
            d["warnings"].append({"code": code, "text": norm(text)})
        elif cls == TLCBUG:
            d["bug"] = True
            d["error_codes"].append(code)
            d["errors"].append({"code": code, "text": norm(text)})
    tail = stdout[pos:]
    if started:
        d["output"] += [norm(l) for l in tail.splitlines() if l.strip()]
    if sany_chunks:
        raw = "".join(sany_chunks)
        m = SANY_ERR_START.search(raw)
        d["sany_errors"] = norm(raw[m.start():]) if m else None
    return d


def parse_sany(stdout: str, rc) -> dict:
    """Normalize the output of `tla2sany.SANY -error-codes FILE` (or `tlc-rs sany -error-codes FILE`)."""
    status = {0: "ok", 2: "syntax_error", 4: "semantic_error"}.get(rc, "error")
    markers = sorted({k for s, k in SANY_MARKERS if s in stdout})
    m = SANY_ERR_START.search(stdout)
    msg = norm(stdout[m.start():]) if m else ""
    # modules in the order SANY analysed them (dependency order): proves real module resolution
    modules = re.findall(r"(?m)^Semantic processing of module (\S+)", stdout)
    # files in the order SANY parsed them (module discovery order); only the module name is kept
    files = [re.split(r"[\\/]", f)[-1][:-4]
             for f in re.findall(r"(?m)^Parsing file (.+?\.tla)(?= |\r?$)", stdout)]
    return {"exit_code": rc, "status": status, "markers": markers, "modules": modules, "files": files, "msg": msg}
