def load_json(p: Path):
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except Exception:
        return None


def rel(p: Path) -> str:
    return Path(p).resolve().relative_to(ROOT).as_posix()


def ensure_java_home():
    d = JAVA_HOME_DIR / ".tlaplus"
    d.mkdir(parents=True, exist_ok=True)
    f = d / "esc.txt"
    if not f.exists() or f.read_text().strip() != "NO_STATISTICS":
        f.write_text("NO_STATISTICS\n")  # opt out of TLC execution statistics (no network reporting)


def java_base(main_class: str) -> list[str]:
    ensure_java_home()
    cp = CP_SEP.join(str(p) for p in [JAR_TLA2TOOLS, JAR_COMMUNITY, TLA_LIBRARY_DIR])
    return ["java", "-XX:+UseParallelGC", "-Xmx6g", f"-Duser.home={JAVA_HOME_DIR}",
            "-Dutil.ExecutionStatisticsCollector.id=NO_STATISTICS",
            "-Dstdout.encoding=UTF-8", "-Dstderr.encoding=UTF-8", "-Dfile.encoding=UTF-8",
            "-cp", cp, main_class]


def rust_base(sub: str) -> list[str]:
    cmd = [str(RUST_BIN)]
    for d in LIB_DIRS:
        cmd += ["--lib", str(d)]
    return cmd + [sub]


def sany_args(entry: dict, syntax_only: bool = False) -> list[str]:
    """`-s` = parse only (no semantic analysis / level checking): the `syntax` level."""
    return (["-s"] if syntax_only else []) + ["-error-codes", str(ROOT / entry["path"])]


def sany_cwd(entry: dict) -> Path:
    """Standalone SANY resolves sibling modules relative to the current directory -> run it in the module's dir."""
    return (ROOT / entry["path"]).parent


def tlc_args(entry: dict, metadir: Path) -> list[str]:
    a = list(TLC_FIXED_ARGS) + ["-metadir", str(metadir)]
    if entry.get("no_deadlock"):
        a.append("-deadlock")   # TLC's -deadlock flag DISABLES deadlock checking
    a += entry.get("extra_args", [])
    if entry.get("config"):
        a += ["-config", str(ROOT / entry["config"])]
    return a + [str(ROOT / entry["spec"])]


def run_proc(cmd: list[str], timeout_s: float, cwd: Path = ROOT, env=None):
    """Run a process; returns (returncode|None on timeout, stdout, stderr, elapsed_ms)."""
    t0 = time.perf_counter()
    try:
        p = subprocess.Popen(cmd, cwd=str(cwd), stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                             stdin=subprocess.DEVNULL, env=env)
    except FileNotFoundError as e:
        return -999, "", str(e), 0.0
    try:
        out, err = p.communicate(timeout=timeout_s)
        rc = p.returncode
    except subprocess.TimeoutExpired:
        kill_tree(p)
        out, err = p.communicate()
        rc = None
    ms = (time.perf_counter() - t0) * 1000.0
    if rc is not None and rc > 2**31:
        rc -= 2**32  # Windows reports exit(-1) as 4294967295
    return rc, out.decode("utf-8", "replace"), err.decode("utf-8", "replace"), ms


def kill_tree(p: subprocess.Popen):
    if os.name == "nt":
        subprocess.run(["taskkill", "/F", "/T", "/PID", str(p.pid)], capture_output=True)
    else:
        p.kill()


class Scratch:
    """A fresh temporary working directory (cwd + metadir for one run); removed afterwards."""

    def __init__(self, tag: str):
        TMP.mkdir(parents=True, exist_ok=True)
        self.dir = Path(tempfile.mkdtemp(prefix=tag[:40].replace("/", "_") + "-", dir=str(TMP)))
        self.meta = self.dir / "meta"

    def __enter__(self):
        return self

    def __exit__(self, *a):
        shutil.rmtree(self.dir, ignore_errors=True)


