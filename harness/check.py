"""Compare tlc-rs (Rust) against the Java TLC 1.8.0 golden outputs.

THIS IS THE ONLY SCORE THAT MATTERS. Do not edit this file, tlcout.py, common.py or the goldens from the loop.

Usage (from repo root):
  python harness/check.py                      # build release + run everything, print the scoreboard
  python harness/check.py --quick              # smoke subset (harness/quick.txt), ~1 minute
  python harness/check.py --kind parse         # only the SANY corpus (or --kind check: only TLC models)
  python harness/check.py --filter ewd998      # only ids containing the substring
  python harness/check.py --id ex/acp/ACP_NB_TLC --verbose    # detailed Java-vs-Rust diff for one entry
  python harness/check.py --failing            # only entries that were not fully passing in the last full run
  python harness/check.py --perf               # sequential run (-j 1) for trustworthy timings
  python harness/check.py --heavy              # also run the heavy models (Java > 60 s), skipped by default
  python harness/check.py --gate               # exit 1 if anything that passed in best.json now fails
  python harness/check.py --update-best        # record current passes as the new baseline (refused on regression)

Levels for SANY modules (corpus "parse"):
  syntax     `SANY -s` (parse only): exit code, error kind and the files parsed (discovery order) equal Java
  parse      SANY exit code, error kind (parse error / semantic error / missing module ...) and the modules
             analysed ("Semantic processing of module X", in order) equal Java
  parse_msg  parse ok AND the normalized SANY error text equals Java (trivially true when Java had no error)
Levels for TLC models (corpus "check"), each one requires the previous one:
  front      same outcome up to "Computing initial states": parse, .cfg, constants, ASSUME
             (if Java stopped earlier: same exit code and same first error code)
  init       same number of distinct initial states (or same early error)
  verdict    same exit code, first error code, violated invariant/property name; on success the same
             states generated / distinct states / depth; for BFS counterexamples the same trace length
  trace      verdict ok AND identical (whitespace-normalized) error texts, counterexample states and action
             labels, lasso tail, final statistics, warnings and Print/PrintT output
  perf       verdict ok AND rust_wall_ms <= 1.10 * java_wall_ms + 50     (not gated: timing noise)
"""
from __future__ import annotations

import argparse
import csv
import json
import os
import subprocess
import sys
import time
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime
from pathlib import Path

from common import (GOLDEN_CHECK, GOLDEN_PARSE, HARNESS, RESULTS_DIR, ROOT, RUST_BIN, Scratch, golden_name,
                    load_corpus, load_json, run_proc, rust_base, sany_args, sany_cwd, tlc_args)
from tlcout import BFS_TRACE_EXITS, parse_sany, parse_tlc

PERF_FACTOR, PERF_SLACK_MS = 1.10, 50.0
HEAVY_MS = 60000
NOT_PORTED_CODE = 9999   # tlc-rs reports "not implemented yet" with this message code (see SCHEMA.md)
PANIC_CODE = 9998        # tlc-rs reports a Rust panic with this message code
LATEST = RESULTS_DIR / "latest.json"
BEST = RESULTS_DIR / "best.json"
HISTORY = RESULTS_DIR / "history.csv"
QUICK = HARNESS / "quick.txt"
PARSE_LEVELS = ["syntax", "parse", "parse_msg"]
CHECK_LEVELS = ["front", "init", "verdict", "trace", "perf"]
GATED = ["syntax", "parse", "parse_msg", "front", "init", "verdict", "trace"]
TRACE_FIELDS = ["errors", "trace", "trace_tail", "generated", "distinct", "left", "depth", "outdegree",
                "warnings", "output", "init_generated"]


# ----------------------------------------------------------------------------- running

def build() -> bool:
    env = dict(os.environ)
    env["PATH"] = str(Path.home() / ".cargo" / "bin") + os.pathsep + env.get("PATH", "")
    r = subprocess.run(["cargo", "build", "--release", "--bin", "tlc-rs"], cwd=str(ROOT), env=env,
                       capture_output=True, text=True, encoding="utf-8", errors="replace")
    if r.returncode != 0:
        lines = [l for l in r.stderr.splitlines() if l.strip()]
        print("BUILD FAILED (cargo build --release). Last lines:")
        print("\n".join(lines[-40:]))
        return False
    return True


def java_ms(g):
    ms = [g.get("wall_ms"), g.get("wall_ms_2")]
    return min(float(x) for x in ms if x is not None)


def run_rust_parse(e):
    rc, out, err, ms = run_proc(rust_base("sany") + sany_args(e), 60, cwd=sany_cwd(e))
    if rc is None:
        return {"status": "timeout", "ms": ms}
    r = {"status": "ok", "ms": ms, "parsed": parse_sany(out, rc), "stderr": err[-800:]}
    rc, out, err, ms = run_proc(rust_base("sany") + sany_args(e, syntax_only=True), 60, cwd=sany_cwd(e))
    r["syntax"] = parse_sany(out, rc) if rc is not None else None
    return r


def run_rust_check(e, g):
    tmo = min(600.0, max(10.0, 3.0 * java_ms(g) / 1000.0 + 10.0))
    with Scratch(e["id"]) as s:
        rc, out, err, ms = run_proc(rust_base("tlc") + tlc_args(e, s.meta), tmo, cwd=s.dir)
    if rc is None:
        return {"status": "timeout", "ms": ms, "timeout_s": tmo}
    p = parse_tlc(out, rc)
    st = "ok" if p["messages"] else "crash"
    return {"status": st, "ms": ms, "parsed": p, "stderr": err[-800:], "stdout_tail": out[-600:] if st != "ok" else ""}


# ----------------------------------------------------------------------------- scoring

def score_parse(e, g, r):
    rec = {"id": e["id"], "kind": "parse", "lines": e["lines"], "java": g["parsed"]["status"],
           "rust": r.get("parsed", {}).get("status", r["status"]), "levels": {}}
    jp, rp = g["parsed"], r.get("parsed")
    js, rs = g.get("syntax"), r.get("syntax")
    rec["levels"]["syntax"] = bool(js and rs) and all(rs[k] == js[k] for k in ("exit_code", "markers", "files"))
    ok = (bool(rp) and rp["exit_code"] == jp["exit_code"] and rp["markers"] == jp["markers"]
          and rp["modules"] == jp["modules"])
    rec["levels"]["parse"] = ok
    rec["levels"]["parse_msg"] = ok and (jp["exit_code"] == 0 or rp["msg"] == jp["msg"])
    if not ok:
        rec["why"] = (f"exit java={jp['exit_code']} rust={rp['exit_code']} markers java={jp['markers']} rust={rp['markers']}"
                      + ("" if rp["modules"] == jp["modules"] else
                         f" modules java={jp['modules'][:6]} rust={rp['modules'][:6]}")
                      if rp else f"rust {r['status']}")
        if rp and rp.get("msg"):
            rec["why"] += f" | rust: {rp['msg'][:160]}"
    elif not rec["levels"]["parse_msg"]:
        rec["why"] = f"msg java={jp['msg'][:120]!r} rust={rp['msg'][:120]!r}"
    if not rec["levels"]["syntax"]:
        rec["why"] = ("[-s] " + (f"exit java={js['exit_code']} rust={rs['exit_code']} markers java={js['markers']} "
                                f"rust={rs['markers']} files java={js['files'][:6]} rust={rs['files'][:6]}"
                                if js and rs else ("golden has no -s run" if not js else "rust -s timeout")) + (f" | rust: {rs['msg'][:140]}" if rs and rs.get("msg") else ""))
    return rec


def rust_label(r):
    p = r.get("parsed")
    if not p:
        return r["status"]
    if NOT_PORTED_CODE in p["error_codes"]:
        return "not_ported"
    if PANIC_CODE in p["error_codes"]:
        return "panic"
    return p["exit_name"]


def first_diff(j, r):
    for k in TRACE_FIELDS:
        if j.get(k) != r.get(k):
            if k == "trace":
                if len(j["trace"]) != len(r["trace"]):
                    return f"trace length java={len(j['trace'])} rust={len(r['trace'])}"
                for i, (a, b) in enumerate(zip(j["trace"], r["trace"])):
                    if a != b:
                        if a["label"] != b["label"]:
                            return f"trace[{i}].label java={a['label'][:80]!r} rust={b['label'][:80]!r}"
                        for v in a["vars"]:
                            if a["vars"].get(v) != b["vars"].get(v):
                                return f"trace[{i}].{v} java={a['vars'][v][:70]!r} rust={str(b['vars'].get(v))[:70]!r}"
                        return f"trace[{i}] vars java={list(a['vars'])} rust={list(b['vars'])}"
            return f"{k} java={json.dumps(j.get(k))[:110]} rust={json.dumps(r.get(k))[:110]}"
    return None


def score_check(e, g, r):
    jp, rp = g["parsed"], r.get("parsed")
    rec = {"id": e["id"], "kind": "check", "lines": e["lines"], "java": jp["exit_name"], "rust": rust_label(r),
           "java_ms": round(java_ms(g), 1), "rust_ms": round(r["ms"], 1), "levels": {k: False for k in CHECK_LEVELS}}
    if not rp:
        rec["why"] = f"rust {r['status']}: " + " | ".join((r.get("stderr") or r.get("stdout_tail") or "").strip()
                                                          .splitlines()[-3:])[-200:]
        return rec
    same_early = rp["exit_code"] == jp["exit_code"] and rp["first_error"] == jp["first_error"]
    lv = rec["levels"]
    lv["front"] = (rp["reached_init"] == jp["reached_init"]) and (jp["reached_init"] or same_early)
    if jp["init_distinct"] is not None:
        lv["init"] = lv["front"] and rp["init_distinct"] == jp["init_distinct"]
    else:
        lv["init"] = lv["front"] and same_early
    v = lv["init"] and same_early and rp["violation"] == jp["violation"]
    if v and jp["exit_code"] == 0:
        v = (rp["generated"], rp["distinct"], rp["depth"]) == (jp["generated"], jp["distinct"], jp["depth"])
    if v and jp["exit_code"] in BFS_TRACE_EXITS:
        v = len(rp["trace"]) == len(jp["trace"])
    lv["verdict"] = v
    nondet = set(g.get("nondet") or [])
    tdiff = first_diff({k: jp.get(k) for k in TRACE_FIELDS if k not in nondet},
                       {k: rp.get(k) for k in TRACE_FIELDS if k not in nondet})
    lv["trace"] = v and tdiff is None
    lv["perf"] = v and r["ms"] <= PERF_FACTOR * java_ms(g) + PERF_SLACK_MS
    rec["ratio"] = round(r["ms"] / max(java_ms(g), 1.0), 3)
    if not lv["front"]:
        rec["why"] = (f"reached_init java={jp['reached_init']} rust={rp['reached_init']}; exit java={jp['exit_code']} "
                      f"rust={rp['exit_code']}; first_error java={jp['first_error']} rust={rp['first_error']}; "
                      f"rust errors: {json.dumps(rp['errors'])[:160]}")
    elif not lv["init"]:
        rec["why"] = f"init_distinct java={jp['init_distinct']} rust={rp['init_distinct']}; exit java={jp['exit_code']} rust={rp['exit_code']}"
    elif not v:
        rec["why"] = (f"exit {jp['exit_code']}/{rp['exit_code']} first_error {jp['first_error']}/{rp['first_error']} "
                      f"violation {jp['violation']}/{rp['violation']} states {jp['generated']}/{rp['generated']} "
                      f"distinct {jp['distinct']}/{rp['distinct']} depth {jp['depth']}/{rp['depth']} "
                      f"trace_len {len(jp['trace'])}/{len(rp['trace'])}  (java/rust)")
    elif tdiff:
        rec["why"] = tdiff
    return rec


# ----------------------------------------------------------------------------- reporting

def git_rev():
    try:
        r = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=str(ROOT), capture_output=True, text=True)
        return r.stdout.strip() or "-"
    except Exception:
        return "-"


def fail_rank(rec):
    """(order, line) - fix in this order: parse, front, init, verdict, parse_msg, trace, perf; small first."""
    lv = rec["levels"]
    order = (["syntax", "parse", "front", "init", "verdict", "parse_msg", "trace", "perf"])
    for i, k in enumerate(order):
        if k in lv and not lv[k]:
            return i, k
    return None


def print_verbose(e, g, r):
    jp, rp = g.get("parsed") or {}, r.get("parsed") or {}
    print(f"===== {e['id']}   java {g.get('wall_ms')} ms   rust {round(r.get('ms', 0), 1)} ms   rust status {r['status']}")
    for k in sorted(set(jp) | set(rp)):
        if k in ("trace",):
            continue
        a, b = jp.get(k), rp.get(k)
        mark = "  " if a == b else "!="
        print(f"  {mark} {k:16s} java={json.dumps(a)[:150]}")
        if a != b:
            print(f"     {'':16s} rust={json.dumps(b)[:150]}")
    jt, rt = jp.get("trace") or [], rp.get("trace") or []
    if jt or rt:
        print(f"  trace: java {len(jt)} states, rust {len(rt)} states")
        for i in range(max(len(jt), len(rt))):
            a = jt[i] if i < len(jt) else None
            b = rt[i] if i < len(rt) else None
            mark = "  " if a == b else "!="
            print(f"  {mark} [{i}] java={json.dumps(a)[:200]}")
            if a != b:
                print(f"         rust={json.dumps(b)[:200]}")
    if r.get("stderr"):
        print("  rust stderr (tail): " + " | ".join(r["stderr"].strip().splitlines()[-5:])[-500:])


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--quick", action="store_true")
    ap.add_argument("--kind", choices=["parse", "check"])
    ap.add_argument("--filter")
    ap.add_argument("--id")
    ap.add_argument("--failing", action="store_true")
    ap.add_argument("--perf", action="store_true")
    ap.add_argument("--heavy", action="store_true")
    ap.add_argument("-j", type=int, default=None)
    ap.add_argument("--no-build", action="store_true")
    ap.add_argument("--top", type=int, default=25)
    ap.add_argument("--verbose", action="store_true")
    ap.add_argument("--gate", action="store_true")
    ap.add_argument("--update-best", action="store_true")
    a = ap.parse_args()
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

    corpus = load_corpus()
    quick = ({l.strip() for l in QUICK.read_text(encoding="utf-8").splitlines() if l.strip() and not l.startswith("#")}
             if a.quick else None)
    entries, goldens, skipped = [], {}, {"timeout": 0, "unscored": 0, "heavy": 0, "missing": 0}
    for kind, gdir in (("parse", GOLDEN_PARSE), ("check", GOLDEN_CHECK)):
        if a.kind and a.kind != kind:
            continue
        for e in corpus[kind]:
            if (quick is not None and e["id"] not in quick) or (a.filter and a.filter not in e["id"]) \
                    or (a.id and e["id"] != a.id):
                continue
            g = load_json(gdir / golden_name(e["id"]))
            if g is None:
                skipped["missing"] += 1
                continue
            if g.get("status") != "ok" or not g.get("parsed"):
                skipped["timeout"] += 1
                continue
            if g.get("unscored"):
                skipped["unscored"] += 1
                continue
            if kind == "check" and java_ms(g) > HEAVY_MS and not (a.heavy or a.id):
                skipped["heavy"] += 1
                continue
            entries.append((kind, e))
            goldens[(kind, e["id"])] = g
    if a.failing:
        prev = load_json(LATEST) or {}
        bad = {(r["kind"], r["id"]) for r in prev.get("records", []) if not all(r["levels"].values())}
        if prev:
            entries = [x for x in entries if (x[0], x[1]["id"]) in bad]
    if not entries:
        print("no entries selected (goldens generated? id spelled right? see harness/README in CLAUDE.md)")
        return 2
    if not a.no_build and not build():
        return 2
    if not RUST_BIN.exists():
        print(f"missing {RUST_BIN}")
        return 2
    jobs = 1 if a.perf else (a.j or max(1, min(8, (os.cpu_count() or 2) // 2)))
    t0 = time.time()

    def job(x):
        kind, e = x
        g = goldens[(kind, e["id"])]
        if kind == "parse":
            r = run_rust_parse(e)
            rec = score_parse(e, g, r) if r.get("parsed") else {"id": e["id"], "kind": "parse", "lines": e["lines"],
                                                                 "java": g["parsed"]["status"], "rust": r["status"],
                                                                 "levels": {k: False for k in PARSE_LEVELS},
                                                                 "why": f"rust {r['status']}"}
        else:
            r = run_rust_check(e, g)
            rec = score_check(e, g, r)
        return kind, e, g, r, rec

    # checks first (they are slower), each kind smallest first
    order = sorted(entries, key=lambda x: (x[0] != "check", x[1]["lines"]))
    with ThreadPoolExecutor(max_workers=jobs) as ex:
        out = list(ex.map(job, order))
    elapsed = time.time() - t0
    recs = [o[4] for o in out]
    if a.verbose:
        for kind, e, g, r, rec in out:
            print_verbose(e, g, r)

    # ------------------------------------------------------------------ scoreboard
    keys = {lvl: set() for lvl in PARSE_LEVELS + CHECK_LEVELS}
    for rec in recs:
        for lvl, ok in rec["levels"].items():
            if ok:
                keys[lvl].add(rec["id"])
    n_parse = sum(1 for r in recs if r["kind"] == "parse")
    n_check = sum(1 for r in recs if r["kind"] == "check")
    jt = sum(r["java_ms"] for r in recs if r["kind"] == "check" and r["levels"]["verdict"])
    rt = sum(r["rust_ms"] for r in recs if r["kind"] == "check" and r["levels"]["verdict"])
    hist = {}
    for r in recs:
        if r["kind"] == "check":
            hist[r["rust"]] = hist.get(r["rust"], 0) + 1
    sk = ", ".join(f"{v} {k}" for k, v in skipped.items() if v)
    print(f"=== tlc-rs vs java-tlc-1.8.0: {n_parse} modules, {n_check} models  (skipped: {sk or 'none'})  "
          f"[{elapsed:.1f}s, -j{jobs}] ===")
    if n_parse:
        print(f"syntax    : {len(keys['syntax']):4d}/{n_parse}   SANY -s (parse only): exit code, error kind, files parsed")
        print(f"parse     : {len(keys['parse']):4d}/{n_parse}   SANY: exit code, error kind, modules analysed")
        print(f"parse_msg : {len(keys['parse_msg']):4d}/{n_parse}   SANY error text")
    if n_check:
        print(f"front     : {len(keys['front']):4d}/{n_check}   same outcome up to 'Computing initial states'")
        print(f"init      : {len(keys['init']):4d}/{n_check}   same number of distinct initial states")
        print(f"verdict   : {len(keys['verdict']):4d}/{n_check}   exit code, first error, violated property, state counts")
        print(f"trace     : {len(keys['trace']):4d}/{n_check}   identical counterexample / error text / output")
        print(f"perf      : {len(keys['perf']):4d}/{n_check}   verdict ok AND rust <= {PERF_FACTOR}*java+{PERF_SLACK_MS:.0f}ms")
        if jt:
            print(f"time      : rust {rt / 1000:.2f}s vs java {jt / 1000:.2f}s over verdict-matching models "
                  f"(x{rt / max(jt, 1e-9):.2f})")
        print(f"rust result histogram: {dict(sorted(hist.items(), key=lambda kv: -kv[1]))}")

    fails = []
    for r in recs:
        fr = fail_rank(r)
        if fr:
            i, lvl = fr
            extra = f" (rust {r['rust_ms']}ms vs java {r['java_ms']}ms, x{r.get('ratio')})" if lvl == "perf" else ""
            sort2 = -(r.get("ratio") or 0) if lvl == "perf" else r["lines"]
            fails.append((i, sort2, f"[{lvl:9s}] {r['id']}: java={r['java']} rust={r['rust']}{extra}  "
                                    f"{(r.get('why') or '')[:230]}"))
    fails.sort(key=lambda x: (x[0], x[1]))
    if fails:
        print(f"--- top failures ({len(fails)} total; fix in this order) ---")
        for _, _, f in fails[:a.top]:
            print("  " + f)

    best = load_json(BEST)
    # parse-corpus and check-corpus ids may coincide (module X.tla and model X.cfg): track them per kind
    evaluated = {(r["kind"], r["id"]) for r in recs}
    regress = []
    if best:
        for lvl in GATED:
            kind = "parse" if lvl in PARSE_LEVELS else "check"
            for k in best.get(lvl, []):
                if (kind, k) in evaluated and k not in keys[lvl]:
                    regress.append(f"{lvl}:{k}")
    if regress:
        print(f"!!! REGRESSIONS vs best.json ({len(regress)}): " + ", ".join(regress[:15]))
    else:
        print("regressions vs best.json: none")

    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    full_run = not (a.quick or a.filter or a.id or a.failing or a.kind)
    if full_run or not LATEST.exists():
        LATEST.write_text(json.dumps({"time": datetime.now().isoformat(timespec="seconds"), "rev": git_rev(),
                                      "records": recs}, indent=1), encoding="utf-8")
    new_hist = not HISTORY.exists()
    with HISTORY.open("a", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        if new_hist:
            w.writerow(["time", "rev", "scope", "modules", "syntax", "parse", "parse_msg", "models", "front", "init", "verdict",
                        "trace", "perf", "rust_s", "java_s", "regressions"])
        scope = "full" if full_run else ("quick" if a.quick else "partial")
        w.writerow([datetime.now().isoformat(timespec="seconds"), git_rev(), scope, n_parse, len(keys["syntax"]), len(keys["parse"]),
                    len(keys["parse_msg"]), n_check, len(keys["front"]), len(keys["init"]), len(keys["verdict"]),
                    len(keys["trace"]), len(keys["perf"]), round(rt / 1000, 3), round(jt / 1000, 3), len(regress)])
    if a.update_best:
        if regress:
            print("refusing --update-best: there are regressions")
        else:
            merged = {lvl: sorted(set((best or {}).get(lvl, [])) | keys[lvl]) for lvl in PARSE_LEVELS + CHECK_LEVELS}
            BEST.write_text(json.dumps(merged, indent=0), encoding="utf-8")
            print("best.json updated: " + ", ".join(f"{k}={len(v)}" for k, v in merged.items()))
    if a.gate and regress:
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
