//! Parallel breadth-first exploration for `-workers N` (N > 1).
//!
//! Not a port of a Java file: Java's `Worker` threads share one state queue and one fingerprint set; here the evaluator is
//! `Rc`/`RefCell` based and cannot be shared, so every worker thread builds its own `Setup` (SANY + spec processing, through the
//! `Factory`) and the threads exchange only encoded states (`tlc_core::senc`) and fingerprints.
//!
//! The search is level-synchronous: all workers expand the states of one level (claiming chunks of the level's states), insert
//! the fingerprints of the successors into one sharded set, collect the new states of their own into a private arena and meet at a
//! barrier before the next level starts.  Therefore the totals (states generated, distinct states, depth) are those of the
//! sequential search; only the per-state out-degrees depend on which worker met a state first.
//!
//! The pass only ever *completes* an exploration.  Everything that needs Java's exact behaviour (an invariant violation, a
//! deadlock, any evaluation error, output of `Print`, `TLCSet` registers, a value that cannot be encoded, a panic ...) makes
//! [`explore`] return `None`; the sequential search (`bfs.rs`) then continues from the level where the parallel pass started and
//! produces the message and the trace exactly as `-workers 1` does.

use crate::bfs::{publish_ev_stats, state_check_invariants, state_fp, state_in_model, step_action_ok, step_check_implied_actions, FpSet};
use std::cell::RefCell;
use std::panic::{catch_unwind, AssertUnwindSafe};
use std::rc::Rc;
use std::sync::atomic::{AtomicBool, AtomicU32, AtomicU64, AtomicUsize, Ordering::*};
use std::sync::{Arc, Barrier, Mutex};
use tlc_core::actions::Mode;
use tlc_core::eval::{LabelBase, LabelSpec};
use tlc_core::senc::{decode_state, encode_state};
use tlc_core::spec::Setup;
use tlc_core::symmetry::{self, SymGroup};
use tlc_core::value::*;
use tlc_core::TlcOptions;

/// builds a fresh `Setup` (the evaluator state of one thread) for the specification being checked
pub type Factory<'a> = &'a (dyn Fn() -> Option<Setup> + Sync);

/// the stack of a worker thread (the same as the thread of the sequential search, see `tlc-cli`)
const WORKER_STACK: usize = 512 * 1024 * 1024;
/// number of fingerprint shards (the top byte of the fingerprint selects the shard; the shard's table uses the low bits)
const SHARDS: usize = 256;

/// encoded states, back to back
#[derive(Default)]
pub(crate) struct Arena {
    data: Vec<u8>,
    /// `offs[i]` = start of state `i` in `data` (it ends where state `i + 1` starts)
    offs: Vec<usize>,
}

impl Arena {
    /// appends the state `f` writes; `false` (nothing appended) if `f` fails
    pub(crate) fn push_with(&mut self, f: impl FnOnce(&mut Vec<u8>) -> bool) -> bool {
        let start = self.data.len();
        if f(&mut self.data) {
            self.offs.push(start);
            true
        } else {
            self.data.truncate(start);
            false
        }
    }
    pub(crate) fn push_state(&mut self, vals: &[Value]) -> bool {
        self.push_with(|d| encode_state(vals, d))
    }
    fn len(&self) -> usize {
        self.offs.len()
    }
    fn get(&self, i: usize) -> &[u8] {
        let s = self.offs[i];
        let e = self.offs.get(i + 1).copied().unwrap_or(self.data.len());
        &self.data[s..e]
    }
}

/// the states of one level, in several arenas
struct Frontier {
    arenas: Vec<Arena>,
    /// `prefix[k]` = number of states in the arenas before arena `k` (one entry more than there are arenas)
    prefix: Vec<usize>,
}

impl Frontier {
    fn new(arenas: Vec<Arena>) -> Frontier {
        let mut prefix = Vec::with_capacity(arenas.len() + 1);
        let mut n = 0;
        for a in &arenas {
            prefix.push(n);
            n += a.len();
        }
        prefix.push(n);
        Frontier { arenas, prefix }
    }
    fn total(&self) -> usize {
        self.prefix[self.prefix.len() - 1]
    }
    fn get(&self, i: usize) -> &[u8] {
        let k = self.prefix.partition_point(|&p| p <= i) - 1;
        self.arenas[k].get(i - self.prefix[k])
    }
}

#[repr(align(64))]
struct Shard(Mutex<FpSet>);

pub(crate) struct Params<'a> {
    pub factory: Factory<'a>,
    pub opts: &'a TlcOptions,
    pub workers: usize,
    /// `-deadlock` is on and the specification asks for it
    pub check_deadlock: bool,
    pub nvars: usize,
    pub start: std::time::Instant,
    /// the states to expand (all of the same level, in queue order), their level
    pub frontier: Arena,
    pub level: u32,
    /// the fingerprints of every state seen so far
    pub seen: &'a FpSet,
    pub base_generated: u64,
    pub base_distinct: u64,
    pub base_max_level: u32,
}

pub(crate) struct Outcome {
    /// successors generated by the expanded states
    pub generated: u64,
    /// states found that were not known before
    pub new_distinct: u64,
    /// the deepest level that has a state
    pub max_level: u32,
    /// per expanded state: the number of successors it found first
    pub outdeg: Vec<u32>,
}

struct Shared<'a> {
    factory: Factory<'a>,
    opts: &'a TlcOptions,
    nworkers: usize,
    check_deadlock: bool,
    nvars: usize,
    start: std::time::Instant,
    fps: Vec<Shard>,
    frontier: Mutex<Arc<Frontier>>,
    /// next state of the frontier to hand out
    cursor: AtomicUsize,
    level: AtomicU32,
    max_level: AtomicU32,
    abort: AtomicBool,
    done: AtomicBool,
    /// the arenas the workers filled during the current level
    parts: Mutex<Vec<Arena>>,
    barrier: Barrier,
    generated: AtomicU64,
    distinct: AtomicU64,
    base_generated: u64,
    base_distinct: u64,
}

impl Shared<'_> {
    /// true if the fingerprint was not yet present
    fn insert(&self, fp: u64) -> bool {
        let fp = if fp == 0 { 1 } else { fp };
        self.fps[(fp >> 56) as usize % SHARDS].0.lock().unwrap().insert(fp)
    }
}

/// what one worker thread owns
struct Ctx {
    setup: Setup,
    perms: SymGroup,
}

#[derive(Default)]
struct Local {
    generated: u64,
    new_distinct: u64,
    outdeg: Vec<u32>,
}

/// Explore everything reachable from `p.frontier`.  `None`: the pass did not complete (see the module comment).
pub(crate) fn explore(p: Params) -> Option<Outcome> {
    let n = p.workers.max(2);
    let fps: Vec<Shard> = (0..SHARDS).map(|_| Shard(Mutex::new(FpSet::with_capacity(1 << 10)))).collect();
    let sh = Shared {
        factory: p.factory,
        opts: p.opts,
        nworkers: n,
        check_deadlock: p.check_deadlock,
        nvars: p.nvars,
        start: p.start,
        fps,
        frontier: Mutex::new(Arc::new(Frontier::new(vec![p.frontier]))),
        cursor: AtomicUsize::new(0),
        level: AtomicU32::new(p.level),
        max_level: AtomicU32::new(p.base_max_level.max(p.level)),
        abort: AtomicBool::new(false),
        done: AtomicBool::new(false),
        parts: Mutex::new(Vec::new()),
        barrier: Barrier::new(n),
        generated: AtomicU64::new(0),
        distinct: AtomicU64::new(0),
        base_generated: p.base_generated,
        base_distinct: p.base_distinct,
    };
    for fp in p.seen.iter() {
        sh.insert(fp);
    }
    let outs: Vec<Option<Vec<u32>>> = std::thread::scope(|s| {
        let handles: Vec<_> = (0..n)
            .map(|_| {
                let sh = &sh;
                std::thread::Builder::new().stack_size(WORKER_STACK).spawn_scoped(s, move || worker_main(sh)).expect("spawn a search thread")
            })
            .collect();
        handles.into_iter().map(|h| h.join().ok()).collect()
    });
    if sh.abort.load(SeqCst) || outs.iter().any(|o| o.is_none()) {
        return None;
    }
    Some(Outcome {
        generated: sh.generated.load(SeqCst),
        new_distinct: sh.distinct.load(SeqCst),
        max_level: sh.max_level.load(SeqCst),
        outdeg: outs.into_iter().flatten().flatten().collect(),
    })
}

/// the evaluator state of one worker: a specification of its own, configured like the sequential search's
fn build_ctx(sh: &Shared) -> Option<Ctx> {
    let setup = (sh.factory)()?;
    publish_ev_stats(&setup, sh.opts);
    setup.ev.start_time.set(Some(sh.start));
    let perms = match &setup.symmetry {
        None => SymGroup::new(Vec::new()),
        Some(top) => {
            let v = setup.run_top(top, &setup.ev.empty(), &setup.ev.empty()).ok()?;
            if !v.is_set_like() {
                return None;
            }
            let (perms, _members) = symmetry::permutation_subgroup_members(&v).ok()?;
            SymGroup::new(perms)
        }
    };
    Some(Ctx { setup, perms })
}

fn worker_main(sh: &Shared) -> Vec<u32> {
    let ctx = catch_unwind(AssertUnwindSafe(|| build_ctx(sh))).ok().flatten();
    if ctx.is_none() {
        sh.abort.store(true, SeqCst);
    }
    sh.barrier.wait();
    let mut loc = Local::default();
    loop {
        let fr: Arc<Frontier> = sh.frontier.lock().unwrap().clone();
        let level = sh.level.load(SeqCst);
        let mut out = Arena::default();
        if let Some(ctx) = &ctx {
            if !sh.abort.load(SeqCst) {
                process_level(ctx, sh, &fr, level, &mut out, &mut loc);
            }
        }
        sh.generated.fetch_add(std::mem::take(&mut loc.generated), SeqCst);
        sh.distinct.fetch_add(std::mem::take(&mut loc.new_distinct), SeqCst);
        sh.parts.lock().unwrap().push(out);
        if sh.barrier.wait().is_leader() {
            advance(sh);
        }
        sh.barrier.wait();
        if sh.done.load(SeqCst) {
            break;
        }
    }
    loc.outdeg
}

/// all workers are at the barrier: the arenas they filled are the next level
fn advance(sh: &Shared) {
    let parts = std::mem::take(&mut *sh.parts.lock().unwrap());
    let next = Frontier::new(parts);
    if sh.abort.load(SeqCst) || next.total() == 0 {
        sh.done.store(true, SeqCst);
        return;
    }
    let level = sh.level.load(SeqCst) + 1;
    sh.level.store(level, SeqCst);
    sh.max_level.store(level, SeqCst);
    sh.cursor.store(0, SeqCst);
    *sh.frontier.lock().unwrap() = Arc::new(next);
}

fn process_level(ctx: &Ctx, sh: &Shared, fr: &Frontier, level: u32, out: &mut Arena, loc: &mut Local) {
    let total = fr.total();
    let chunk = (total / (sh.nworkers * 8)).clamp(1, 128);
    while !sh.abort.load(Relaxed) {
        let a = sh.cursor.fetch_add(chunk, Relaxed);
        if a >= total {
            break;
        }
        for i in a..(a + chunk).min(total) {
            if sh.abort.load(Relaxed) {
                break;
            }
            let r = catch_unwind(AssertUnwindSafe(|| expand(ctx, sh, fr.get(i), level, out, loc)));
            if !matches!(r, Ok(Some(()))) {
                sh.abort.store(true, SeqCst);
                break;
            }
        }
    }
}

/// Expand one state like the loop of the sequential search does (`Checker::run`); `None` where that loop would report something.
fn expand(ctx: &Ctx, sh: &Shared, enc: &[u8], level: u32, out: &mut Arena, loc: &mut Local) -> Option<()> {
    let setup = &ctx.setup;
    let ev = setup.ev.clone();
    let cur = decode_state(enc, sh.nvars)?;
    ev.epoch.set(ev.epoch.get() + 1);
    ev.counters.set([
        level as i64,
        (sh.base_generated + sh.generated.load(Relaxed) + loc.generated) as i64,
        (sh.base_distinct + sh.distinct.load(Relaxed) + loc.new_distinct) as i64,
        0,
        sh.max_level.load(Relaxed) as i64,
        0,
    ]);
    let nx = setup.next.first()?;
    let buf = RefCell::new(vec![Value::Undef; sh.nvars]);
    *ev.cur_label.borrow_mut() =
        Some(LabelSpec { base: Rc::new(LabelBase { name: Arc::from(nx.name.as_str()), params: vec![], pnames: vec![] }), stop: Rc::as_ptr(&nx.ex) as usize });
    ev.splitting.set(false);
    let mut succs: Vec<Vec<Value>> = vec![];
    let mut incomplete = false;
    let r = ev.with_frame(nx.nslots.get(), |ev| {
        ev.enum_action(&nx.ex, Mode::Next, &cur, &buf, &mut || {
            let st = buf.borrow().clone();
            if st.iter().any(|v| matches!(v, Value::Undef)) {
                incomplete = true;
                return Ok(());
            }
            succs.push(st);
            Ok(())
        })
    });
    if r.is_err() || incomplete {
        return None;
    }
    if succs.is_empty() && sh.check_deadlock {
        return None;
    }
    let mut unseen = 0u32;
    for st in succs {
        loc.generated += 1;
        let ok = state_in_model(setup, &st).and_then(|m| if m { step_action_ok(setup, &cur, &st) } else { Ok(false) }).ok()?;
        // Java: a successor outside the model is not stored but its invariants are still checked
        if !ok && !setup.invariants.is_empty() && !matches!(state_check_invariants(setup, &st), Ok(None)) {
            return None;
        }
        if ok {
            let fp = state_fp(setup, &ctx.perms, &st).ok()?;
            if sh.insert(fp) {
                if !matches!(state_check_invariants(setup, &st), Ok(None)) {
                    return None;
                }
                if !out.push_state(&st) {
                    return None;
                }
                unseen += 1;
                loc.new_distinct += 1;
            }
        }
        if !setup.implied_actions.is_empty() && !matches!(step_check_implied_actions(setup, &cur, &st), Ok(None)) {
            return None;
        }
    }
    loc.outdeg.push(unseen);
    // everything with a side effect the sequential search orders (output, warnings, `TLCSet` registers) is left to it
    if !ev.out.borrow().is_empty() || !ev.warnings.borrow().is_empty() || !ev.tlc_registers.borrow().is_empty() || !ev.named_regs.borrow().is_empty() {
        return None;
    }
    Some(())
}
